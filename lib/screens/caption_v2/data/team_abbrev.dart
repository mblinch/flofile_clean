/// Team name → short abbreviation for roster / lane titles.
String mlbTeamAbbreviation(String teamName) {
  final trimmed = teamName.trim();
  if (trimmed.isEmpty) return trimmed;
  if (RegExp(r'^[A-Za-z]{2,4}$').hasMatch(trimmed)) {
    return trimmed.toUpperCase();
  }
  final lower = trimmed.toLowerCase();
  final exact = _abbreviations[lower];
  if (exact != null) return exact;

  String? unique;
  for (final entry in _abbreviations.entries) {
    final matches = entry.key == lower ||
        entry.key.endsWith(' $lower') ||
        lower.endsWith(' ${entry.key}');
    if (!matches) continue;
    if (unique != null && unique != entry.value) return trimmed;
    unique = entry.value;
  }
  return unique ?? trimmed;
}

